// Markdown draft builders for the "Ask the map" workspace.
// Both outputs are DRAFTS for a human to review, edit and act on.
// Neither is sent, posted, registered or broadcast by this app.
// Every figure must trace back to the provided context; unknowns are listed, not hidden.
import {
  toolMonsoonAnalogs,
  toolNrscCoverage,
  toolP90Band,
  toolPeakDischarge,
  toolStorageCandidates,
  type DecisionContext,
} from "./tools.ts";

export type DraftResult = { markdown: string; filename: string };

const line = (s: string) => `${s}\n`;
const disclaimer = `> **DRAFT — generated by TerraScope (local prototype).** Not an official product of any government body. This draft must be reviewed and, where relevant, issued by the authorised officer. TerraScope cannot send, broadcast or authorise anything.\n`;

export function buildPreMonsoonAdvisory(ctx: DecisionContext, audience: string): DraftResult {
  const peak = toolPeakDischarge(ctx);
  const p90 = toolP90Band(ctx);
  const monsoon = toolMonsoonAnalogs(ctx);
  const nrsc = toolNrscCoverage();
  const storage = toolStorageCandidates(ctx, 3);

  let md = "";
  md += line("# Pre-monsoon preparedness brief (DRAFT)");
  md += line("");
  md += line(`**Audience:** ${audience}`);
  md += line(`**Prepared:** ${new Date().toISOString()}`);
  md += line("**Status:** DRAFT for review by the authorised officer — not issued, not an official warning");
  md += line("");
  md += line("## What the local evidence shows");
  md += line("");
  md += line(`- Peak daily discharge in the 2015–2024 local record: ${peak.ok ? `${peak.value.peakM3s.toLocaleString("en-GB")} m³/s (${peak.value.date})` : "not available"} — GloFAS model output, not a gauge record.`);
  md += line(`- Top-10% band over the record: ${p90.ok ? `≥ ${p90.value.p90M3s.toLocaleString("en-GB")} m³/s (${p90.value.aboveCount} of ${p90.value.totalDays} days)` : "not available"} — descriptive percentile, not an alert threshold.`);
  md += line(`- Monsoon rainfall (Jun–Sep) with ENSO context: ${monsoon.ok ? monsoon.value.summary : "not available"}.`);
  md += line(`- Observed satellite imagery: ${nrsc.ok ? nrsc.value.window : "not available"} — outside these dates, observed extent is unknown, never dry.`);
  md += line(`- Terrain screening: ${storage.ok ? `${storage.value.total} candidate depressions catalogued; top geometric capacities ${storage.value.top.map((c) => `${c.label ?? c.id} ${c.capacityM3.toLocaleString("en-GB")} m³`).join("; ")}` : "not run"} — not surveyed reservoirs.`);
  md += line("");
  md += line("## Decisions NOT supported by this evidence");
  md += line("");
  md += line("- No flood depth, timing, extent or inundation boundary is established by this data.");
  md += line("- No safe route, dry area, structure integrity or site suitability is established.");
  md += line("- Evacuation, warnings or orders must not be issued on the basis of this draft alone.");
  md += line("- Storage candidates are geometric depressions only; contributing areas, outlet control, bathymetry, land rights and engineering constraints are unverified.");
  md += line("");
  md += line("## What the authorised officer may reasonably consider");
  md += line("");
  md += line("1. Commissioning field verification of the top screened candidates (outlet, depth, bathymetry, land rights) before any works commitment.");
  md += line("2. Cross-checking the GloFAS cell value against CWC gauge readings for the same days, with the Gandak basin office.");
  md += line("3. Obtaining current issue-time IMD/CWC bulletins for the readiness decision; this workspace is not a bulletin source.");
  md += line("4. Preparing — not issuing — community preparedness communiqués with the district disaster management authority.");
  md += line("");
  md += line("## Unknowns (explicit)");
  md += line("");
  md += line("- Cell-to-reach discharge mapping for the GloFAS sample cell is unverified.");
  md += line("- No gauge rating curve is loaded; no held-out event validation has been performed.");
  md += line("- NRSC observed coverage is limited to 1–2 Oct 2024 within 85.05–85.3E / 25.6–25.85N.");
  md += line("- ENSO context is probabilistic climate background; it is not a local-impact multiplier.");
  md += line("");
  md += disclaimer;
  md += line("");
  md += line("Reviewed and issued by (signature/date): ______________________________");
  return { markdown: md, filename: "pre-monsoon-advisory-draft.md" };
}

export function buildDecisionBrief(ctx: DecisionContext): DraftResult {
  const peak = toolPeakDischarge(ctx);
  const p90 = toolP90Band(ctx);
  const monsoon = toolMonsoonAnalogs(ctx);
  const nrsc = toolNrscCoverage();
  const storage = toolStorageCandidates(ctx, 5);

  let md = "";
  md += line("# Decision brief — Gandak corridor storage preparedness (DRAFT)");
  md += line("");
  md += line(`**Prepared:** ${new Date().toISOString()}`);
  md += line("**Status:** DRAFT for a planning meeting — not approved, not binding");
  md += line("");
  md += line("## Option A — Act on the current screening");
  md += line("");
  md += line(`- Advance the top ${storage.ok && storage.value.top.length ? storage.value.top.length : 0} screened candidates to field survey (outlet, bathymetry, land rights, structures).`);
  md += line("- Consequences if done: modest survey cost; learns which bowls (if any) are real; no flood claim is implied.");
  md += line("- Consequences if false positives: candidate(s) discarded at survey stage; low cost, honest outcome.");
  md += line("");
  md += line("## Option B — Do nothing pending survey of unrelated priorities");
  md += line("");
  md += line("- Consequences: no storage preparedness; same hydrological uncertainty; no learning.");
  md += line("- Consequences if this season brings the record's peak-like flow: no new retention exists; existing embankments/drainage unaltered.");
  md += line("");
  md += line("## Evidence shared by both options");
  md += line("");
  md += line(`- ${peak.ok ? `Record peak ${peak.value.peakM3s.toLocaleString("en-GB")} m³/s on ${peak.value.date}` : "Peak unavailable"}; ${p90.ok ? `top-10% band ≥ ${p90.value.p90M3s.toLocaleString("en-GB")} m³/s` : "band unavailable"}.`);
  md += line(`- Monsoon/ENSO context: ${monsoon.ok ? monsoon.value.summary : "unavailable"}.`);
  md += line(`- Observed imagery window: ${nrsc.ok ? nrsc.value.window : "unavailable"}; anything else is unknown.`);
  md += line("- Capacity figures are geometric, not usable storage; routing, outlet control and soils are unverified.");
  md += line("");
  md += line("## Explicit unknowns");
  md += line("");
  md += line("- Contributing catchment areas are DEM-derived sub-basin values (HydroBASINS v1c), not surveyed; routing is not modeled.");
  md += line("- No calibrated solver has validated depth or travel time; no held-out event test exists yet.");
  md += line("- Land ownership and rights at any candidate are unverified and must come from cadastral sources before works.");
  md += line("");
  md += line("## What a decision still needs");
  md += line("");
  md += line("1. Field survey of 1–3 shortlisted bowls (staff/contractor).");
  md += line("2. Gauge data request to CWC/state board for the replay window (rated discharge + water levels).");
  md += line("3. Councillor/panchayat/landholder engagement before any intervention.");
  md += line("4. Explicit sign-off by the accountable authority; this brief is an input, never the decision.");
  md += line("");
  md += disclaimer;
  md += line("");
  md += line("Won option (circle one): A / B — decided by: ________________ on: ____________");
  return { markdown: md, filename: "decision-brief-draft.md" };
}
